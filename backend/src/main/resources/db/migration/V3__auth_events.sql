CREATE TABLE auth_event (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    type        TEXT        NOT NULL,
    username    TEXT,
    user_id     BIGINT,
    client_ip   TEXT,
    detail      TEXT,

    CONSTRAINT fk_auth_event_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE SET NULL,
    CONSTRAINT ck_auth_event_type CHECK (type IN (
        'LOGIN_SUCCESS', 'LOGIN_FAILURE', 'REFRESH', 'REFRESH_REUSE', 'LOGOUT', 'RATE_LIMITED'
    ))
);

CREATE INDEX ix_auth_event_occurred_at ON auth_event (occurred_at DESC);
CREATE INDEX ix_auth_event_username ON auth_event (username, occurred_at DESC);
